    private static function section(int $n): string
    {
        $paragraphs = '';
        for ($p = 0; $p < 6; $p++) {
            $paragraphs .= "\n        <p class=\"prose\">" . self::text($n * 10 + $p, 90) . '</p>';
        }
        $links = '';
        for ($l = 0; $l < 6; $l++) {
            $links .= "\n            <li><a href=\"/page/$n/$l\" @click.prevent=\"open = !open\" :aria-expanded=\"open\">" . self::text($n + $l, 3) . '</a></li>';
        }
        return "<section class=\"section section--$n\" id=\"s$n\" x-data=\"{ open: false }\" x-on:keydown.escape=\"open = false\">"
            . "\n        <!-- section $n -->"
            . "\n        <h2 class=\"heading\" :class=\"{ 'is-open': open }\">" . self::text($n, 5) . '</h2>'
            . $paragraphs
            . "\n        <ul class=\"links\" x-show=\"open\">$links\n        </ul>"
            . "\n        <img src=\"/assets/image-$n.jpg\" :src=\"open ? '/assets/large-$n.jpg' : '/assets/image-$n.jpg'\" alt=\"\" width=\"800\" height=\"450\" loading=\"lazy\">"
            . "\n    </section>";
    }

    private static function text(int $seed, int $words): string
    {
        $out = [];
        $count = count(self::WORDS);
        for ($i = 0; $i < $words; $i++) {
            $out[] = self::WORDS[($seed * 31 + $i * 7 + intdiv($i, 5)) % $count];
        }
        return ucfirst(implode(' ', $out)) . '.';
    }
