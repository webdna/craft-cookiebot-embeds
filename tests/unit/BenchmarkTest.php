/**
 * The performance budget (section 5, non-functional; BR-5), as tests that fail above it: on a
 * 300 KB page with 40 scripts and 6 iframes the rewrite adds under 5 ms at the median and 15 ms at
 * p95, and the fast exit adds under 0.5 ms.
 *
 * `tests/fixtures/benchmark.html` is generated by `page()` and committed. Regenerate it with
 * `CBE_UPDATE_FIXTURES=1` (which also refreshes its `.expected.html` through RewriterTest). Set
 * `CBE_BENCH=1` to print the timings.
 */
final class BenchmarkTest extends TestCase
{
    private const FIXTURE = __DIR__ . '/../fixtures/benchmark.html';

    private const SIZE = 300 * 1024;

    private const SCRIPTS = 40;

    private const IFRAMES = 6;

    /** Milliseconds. */
    private const MEDIAN_BUDGET = 5.0;

    private const P95_BUDGET = 15.0;

    private const FAST_EXIT_BUDGET = 0.5;

    private const WARM_UP = 5;

    private const RUNS = 60;

    private const WORDS = ['anchor', 'beacon', 'cobalt', 'dynamo', 'ember', 'falcon', 'garden', 'harbour', 'island',
        'juniper', 'kestrel', 'ledger', 'meadow', 'nectar', 'orbit', 'parcel', 'quarry', 'ribbon', 'saddle', 'timber',
        'umber', 'velvet', 'willow', 'yonder', ];

    public function testTheFixtureIsTheGeneratedPage(): void
    {
        if (getenv('CBE_UPDATE_FIXTURES')) {
            file_put_contents(self::FIXTURE, self::page());
        }

        $this->assertFileExists(self::FIXTURE);
        $this->assertSame(self::page(), file_get_contents(self::FIXTURE), 'Regenerate with CBE_UPDATE_FIXTURES=1');
    }

    /**
     * The fixture is the size and shape the budget is stated for, and the rewrite has real work
     * to do on it: gated scripts and iframes, placeholders, and things left alone.
     */
    public function testTheFixtureHasTheBudgetedShape(): void
    {
        $html = self::fixture();

        $this->assertGreaterThanOrEqual(self::SIZE, strlen($html));
        $this->assertLessThan(self::SIZE + 20 * 1024, strlen($html));
        $this->assertSame(self::SCRIPTS, substr_count($html, '<script'));
        $this->assertSame(self::IFRAMES, substr_count($html, '<iframe'));

        $output = self::pipeline($html)->html;
        // Gated: 4 head scripts, 12 body widgets and 4 iframes. Already marked: 4 scripts and 1
        // iframe. The other 20 scripts (Cookiebot, Tag Manager, an inline call with no URL,
        // JSON-LD, an importmap, a module, first-party, necessary and x-templates) are left.
        $this->assertSame(16, substr_count($output, 'type="text/plain"'));
        $this->assertSame(4 + 1, substr_count($output, 'data-cookieblock-src='));
        $this->assertSame(20 + 5, substr_count($output, 'data-cookieconsent="'));
        // One placeholder per gated iframe and per gated body widget; none in the head (BR-16).
        $this->assertSame(4 + 12, substr_count($output, 'data-cbe-placeholder='));
    }

    /**
     * The whole per-request cost, as the render hook will pay it: load the provider list, resolve
     * the config, build the services and rewrite, including the real Twig placeholder.
     */
    public function testTheRewriteIsWithinBudget(): void
    {
        $html = self::fixture();
        $times = [];
        for ($i = 0; $i < self::WARM_UP + self::RUNS; $i++) {
            $start = hrtime(true);
            self::pipeline($html);
            $elapsed = (hrtime(true) - $start) / 1e6;
            if ($i >= self::WARM_UP) {
                $times[] = $elapsed;
            }
        }

        $median = self::percentile($times, 50);
        $p95 = self::percentile($times, 95);
        self::report(sprintf('rewrite: median %.3f ms, p95 %.3f ms over %d runs', $median, $p95, self::RUNS));

        $this->assertLessThan(self::MEDIAN_BUDGET, $median, sprintf('Median %.3f ms', $median));
        $this->assertLessThan(self::P95_BUDGET, $p95, sprintf('p95 %.3f ms', $p95));
    }

    /**
     * BR-5: the same page with every script and iframe removed is returned as it is, fast.
     */
    public function testTheFastExitIsWithinBudget(): void
    {
        $html = (string)preg_replace('~<(script|iframe)\b.*?</\1>~is', '', self::fixture());
        $this->assertStringNotContainsStringIgnoringCase('<script', $html);
        $this->assertStringNotContainsStringIgnoringCase('<iframe', $html);
        $this->assertGreaterThan(250 * 1024, strlen($html));

        $rewriter = self::rewriter(new Vendors(), (new Config())->resolve([], 'default', ['default']));
        $times = [];
        for ($i = 0; $i < self::WARM_UP + self::RUNS; $i++) {
            $start = hrtime(true);
            $result = $rewriter->rewrite($html);
            $elapsed = (hrtime(true) - $start) / 1e6;
            if ($i >= self::WARM_UP) {
                $times[] = $elapsed;
            }
            $this->assertSame($html, $result->html);
        }

        $median = self::percentile($times, 50);
        self::report(sprintf('fast exit: median %.4f ms over %d runs', $median, self::RUNS));

        $this->assertLessThan(self::FAST_EXIT_BUDGET, $median, sprintf('Median %.4f ms', $median));
    }

    private static function pipeline(string $html): RewriteResult
    {
        $vendors = new Vendors();
        $config = (new Config())->resolve([], 'default', ['default']);
        return self::rewriter($vendors, $config)->rewrite($html);
    }

    private static function rewriter(Vendors $vendors, SiteConfig $config): Rewriter
    {
        return new Rewriter(
            new Classifier($config, $vendors, ['www.example.com'], ['assets.example-cdn.net']),
            $vendors,
            $config,
            (new Placeholder())->renderer(),
        );
    }

    private static function fixture(): string
    {
        return (string)file_get_contents(self::FIXTURE);
    }

    /**
     * @param list<float> $values
     */
    private static function percentile(array $values, int $percent): float
    {
        sort($values);
        $index = (int)ceil($percent / 100 * count($values)) - 1;
        return $values[max(0, $index)];
    }

    private static function report(string $line): void
    {
        if (getenv('CBE_BENCH')) {
            fwrite(STDERR, "\n$line\n");
        }
    }

